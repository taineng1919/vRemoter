import Foundation

enum AppStorage {
    /// Optional workspace-only profile for a complete development App.
    /// Normal launches retain the installed application's existing paths.
    static let developmentDirectory: URL? = {
        guard let path = ProcessInfo.processInfo.environment["VREMOTER_DATA_ROOT"],
              path.hasPrefix("/"), path != "/" else { return nil }
        return URL(fileURLWithPath: path, isDirectory: true)
    }()
    static let preferences = AppPreferences(directory: developmentDirectory)

    static let loggingEnabledKey = "loggingEnabled"
    static let recordingEnabledKey = "recordingEnabled"
    static let macInputEnabledKey = "macInputEnabled"
    static let remoteInputEnabledKey = "remoteInputEnabled"
    static let inputTriggerKeyKey = "inputTriggerKey"
    static let functionHoldEnabledKey = "functionHoldEnabled"

    static let logsDirectory: URL = {
        developmentDirectory?.appendingPathComponent("Logs", isDirectory: true)
            ?? FileManager.default.homeDirectoryForCurrentUser
                .appendingPathComponent("Library/Logs/vRemote", isDirectory: true)
    }()

    static let logFile = logsDirectory.appendingPathComponent("vRemote.log")

    static let applicationSupportDirectory: URL = {
        developmentDirectory?.appendingPathComponent("Support", isDirectory: true)
            ?? FileManager.default.homeDirectoryForCurrentUser
                .appendingPathComponent("Library/Application Support/vRemote", isDirectory: true)
    }()

    static let recordingsDirectory = applicationSupportDirectory
        .appendingPathComponent("Recordings", isDirectory: true)

    static func prepare() {
        AppStorage.preferences.register(defaults: [
            loggingEnabledKey: false,
            recordingEnabledKey: false,
            macInputEnabledKey: true,
            remoteInputEnabledKey: true,
            inputTriggerKeyKey: InputTriggerKey.option.rawValue,
            functionHoldEnabledKey: false,
        ])
        ensureDirectory(logsDirectory)
        ensureDirectory(applicationSupportDirectory)
        ensureDirectory(recordingsDirectory)

        // vRemote has its own storage namespace and never touches V1 data.
    }

    static var loggingEnabled: Bool {
        get { AppStorage.preferences.bool(forKey: loggingEnabledKey) }
        set { AppStorage.preferences.set(newValue, forKey: loggingEnabledKey) }
    }

    static var recordingEnabled: Bool {
        get { AppStorage.preferences.bool(forKey: recordingEnabledKey) }
        set { AppStorage.preferences.set(newValue, forKey: recordingEnabledKey) }
    }

    static var macInputEnabled: Bool {
        get { AppStorage.preferences.bool(forKey: macInputEnabledKey) }
        set { AppStorage.preferences.set(newValue, forKey: macInputEnabledKey) }
    }

    static var remoteInputEnabled: Bool {
        get { AppStorage.preferences.bool(forKey: remoteInputEnabledKey) }
        set { AppStorage.preferences.set(newValue, forKey: remoteInputEnabledKey) }
    }

    static var inputTriggerKey: InputTriggerKey {
        get {
            let raw = AppStorage.preferences.string(forKey: inputTriggerKeyKey)
            return InputTriggerKey(rawValue: raw ?? "") ?? .option
        }
        set {
            AppStorage.preferences.set(newValue.rawValue, forKey: inputTriggerKeyKey)
        }
    }

    /// Affects only the synthetic Fn generated by this application.
    static var functionHoldEnabled: Bool {
        get { AppStorage.preferences.bool(forKey: functionHoldEnabledKey) }
        set { AppStorage.preferences.set(newValue, forKey: functionHoldEnabledKey) }
    }

    static func ensureDirectory(_ url: URL) {
        try? FileManager.default.createDirectory(
            at: url,
            withIntermediateDirectories: true
        )
    }

    static func byteSize(of url: URL) -> UInt64 {
        let fm = FileManager.default
        guard let enumerator = fm.enumerator(
            at: url,
            includingPropertiesForKeys: [.isRegularFileKey, .fileSizeKey],
            options: [.skipsHiddenFiles]
        ) else { return 0 }

        var total: UInt64 = 0
        for case let fileURL as URL in enumerator {
            guard let values = try? fileURL.resourceValues(
                forKeys: [.isRegularFileKey, .fileSizeKey]
            ), values.isRegularFile == true else { continue }
            total += UInt64(values.fileSize ?? 0)
        }
        return total
    }

    static func clearFiles(in directory: URL) {
        let fm = FileManager.default
        ensureDirectory(directory)
        guard let files = try? fm.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: nil,
            options: [.skipsHiddenFiles]
        ) else { return }
        for file in files {
            try? fm.removeItem(at: file)
        }
    }

    static func formattedSize(_ bytes: UInt64) -> String {
        ByteCountFormatter.string(
            fromByteCount: Int64(bytes),
            countStyle: .file
        )
    }
}
